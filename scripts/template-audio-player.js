/**
 * ROKKO Records - Template-Based Audio Player Component
 * Reusable audio player matching player_template.png design
 * Can be instantiated for different artists/albums
 */

class TemplateAudioPlayer {
    constructor() {
        this.currentPlaylist = [];
        this.currentArtist = '';
        this.currentTrackIndex = 0;
        this.isPlaying = false;
        this.audioElement = null;
        this.playerOverlay = null;
        
        this.init();
    }
    
    init() {
        // Create player overlay if it doesn't exist
        if (!document.getElementById('templatePlayerOverlay')) {
            this.createPlayerHTML();
        }
        
        // Cache DOM elements
        this.playerOverlay = document.getElementById('templatePlayerOverlay');
        this.audioElement = document.getElementById('templateAudioElement');
        this.closeBtn = document.getElementById('templateCloseBtn');
        this.playBtn = document.getElementById('templatePlayBtn');
        this.prevBtn = document.getElementById('templatePrevBtn');
        this.nextBtn = document.getElementById('templateNextBtn');
        this.progressBarArea = document.getElementById('templateProgressBarArea');
        this.progressIndicator = document.getElementById('templateProgressIndicator');
        this.albumCover = document.getElementById('templateAlbumCover');
        this.trackTitle = document.getElementById('templateTrackTitle');
        this.trackArtist = document.getElementById('templateTrackArtist');
        this.currentTimeEl = document.getElementById('templateCurrentTime');
        this.durationEl = document.getElementById('templateDuration');
        this.playlistArea = document.getElementById('templatePlaylistArea');
        
        // Set volume
        this.audioElement.volume = 0.7;
        
        // Add event listeners
        this.addEventListeners();
    }
    
    createPlayerHTML() {
        const playerHTML = `
        <!-- Template Audio Player Overlay -->
        <div id="templatePlayerOverlay" class="template-player-overlay" style="display: none;">
            <!-- Close Button (Top Right) -->
            <button id="templateCloseBtn" class="template-close-btn" aria-label="Player schließen" title="Schließen">✕</button>

            <!-- Player Container with Template Background -->
            <div class="template-player-container">
                <!-- Template Background Image -->
                <img src="audioplayer/player_template.png" alt="" class="template-bg">

                <!-- Interactive Layer - All clickable/dynamic elements -->
                <div class="template-interactive-layer">
                    <!-- Album Cover (Top Left) -->
                    <div class="template-album-cover-area">
                        <img id="templateAlbumCover" src="" alt="Album Cover">
                    </div>

                    <!-- Track Info (Top Right) -->
                    <div class="template-track-info-area">
                        <h2 id="templateTrackTitle">Track Title</h2>
                        <p id="templateTrackArtist">Artist Name</p>
                    </div>

                    <!-- Time Display (Right Side) -->
                    <div class="template-time-display-area">
                        <span id="templateCurrentTime">0:00</span>/<span id="templateDuration">0:00</span>
                    </div>

                    <!-- Progress Bar -->
                    <div id="templateProgressBarArea" 
                         class="template-progress-bar-area"
                         role="slider"
                         aria-label="Seek"
                         aria-valuemin="0"
                         aria-valuemax="100"
                         aria-valuenow="0"
                         tabindex="0">
                        <div id="templateProgressIndicator" class="template-progress-indicator"></div>
                    </div>

                    <!-- Control Buttons -->
                    <button id="templatePrevBtn" class="template-control-btn template-prev-btn" aria-label="Previous Track" title="Previous"></button>
                    <button id="templatePlayBtn" class="template-control-btn template-play-btn" aria-label="Play" title="Play/Pause"></button>
                    <button id="templateNextBtn" class="template-control-btn template-next-btn" aria-label="Next Track" title="Next"></button>

                    <!-- Playlist (Bottom Left) -->
                    <div id="templatePlaylistArea" class="template-playlist-area">
                        <!-- Generated by JavaScript -->
                    </div>

                    <!-- Streaming Buttons (Bottom Right) -->
                    <div class="template-streaming-buttons-area">
                        <button class="template-streaming-btn" aria-label="Listen on SoundCloud" title="SoundCloud">
                            <img src="img/logo_01.png" alt="SoundCloud">
                        </button>
                        <button class="template-streaming-btn" aria-label="Listen on Amazon Music" title="Amazon Music">
                            <img src="img/logo_02.png" alt="Amazon Music">
                        </button>
                        <button class="template-streaming-btn" aria-label="Listen on Apple Music" title="Apple Music">
                            <img src="img/logo_03.png" alt="Apple Music">
                        </button>
                        <button class="template-streaming-btn" aria-label="Listen on Spotify" title="Spotify">
                            <img src="img/logo_06.png" alt="Spotify">
                        </button>
                    </div>
                </div>
            </div>
        </div>

        <!-- Audio Element -->
        <audio id="templateAudioElement" preload="metadata"></audio>
        `;
        
        document.body.insertAdjacentHTML('beforeend', playerHTML);
    }
    
    /**
     * Open player with a playlist
     * @param {Array} playlist - Array of track objects {title, artist, src, cover}
     * @param {string} artistName - Artist name to display
     * @param {number} startIndex - Track index to start playing (default: 0)
     */
    openPlayer(playlist, artistName = '', startIndex = 0) {
        this.currentPlaylist = playlist;
        this.currentArtist = artistName;
        this.currentTrackIndex = startIndex;
        
        this.buildPlaylist();
        this.loadTrack(this.currentTrackIndex);
        
        this.playerOverlay.style.display = 'flex';
        document.body.style.overflow = 'hidden';
    }
    
    closePlayer() {
        this.playerOverlay.style.display = 'none';
        document.body.style.overflow = '';
        this.pause();
    }
    
    buildPlaylist() {
        this.playlistArea.innerHTML = '';
        
        this.currentPlaylist.forEach((track, index) => {
            const button = document.createElement('button');
            button.className = 'template-playlist-item';
            button.setAttribute('aria-label', `Play ${track.title}`);
            button.textContent = `${index + 1}. ${track.title}`;
            
            if (index === this.currentTrackIndex) {
                button.classList.add('active');
            }
            
            button.addEventListener('click', () => {
                this.loadTrack(index);
                this.play();
            });
            
            this.playlistArea.appendChild(button);
        });
    }
    
    loadTrack(index) {
        if (index < 0 || index >= this.currentPlaylist.length) return;
        
        this.currentTrackIndex = index;
        const track = this.currentPlaylist[index];
        
        this.audioElement.src = track.src;
        this.trackTitle.textContent = track.title;
        this.trackArtist.textContent = track.artist || this.currentArtist;
        this.albumCover.src = track.cover;
        
        this.updatePlaylistActiveState();
        this.progressIndicator.style.width = '0%';
        this.updateTimeDisplay();
    }
    
    updatePlaylistActiveState() {
        const items = this.playlistArea.querySelectorAll('.template-playlist-item');
        items.forEach((item, index) => {
            if (index === this.currentTrackIndex) {
                item.classList.add('active');
            } else {
                item.classList.remove('active');
            }
        });
    }
    
    play() {
        this.audioElement.play()
            .then(() => {
                this.isPlaying = true;
                this.playBtn.setAttribute('aria-label', 'Pause');
            })
            .catch(error => {
                console.error('Error playing audio:', error);
            });
    }
    
    pause() {
        this.audioElement.pause();
        this.isPlaying = false;
        this.playBtn.setAttribute('aria-label', 'Play');
    }
    
    togglePlayPause() {
        if (this.isPlaying) {
            this.pause();
        } else {
            this.play();
        }
    }
    
    previousTrack() {
        let newIndex = this.currentTrackIndex - 1;
        if (newIndex < 0) {
            newIndex = this.currentPlaylist.length - 1;
        }
        this.loadTrack(newIndex);
        if (this.isPlaying) this.play();
    }
    
    nextTrack() {
        let newIndex = this.currentTrackIndex + 1;
        if (newIndex >= this.currentPlaylist.length) {
            newIndex = 0;
        }
        this.loadTrack(newIndex);
        if (this.isPlaying) this.play();
    }
    
    updateProgress() {
        if (this.audioElement.duration) {
            const progressPercent = (this.audioElement.currentTime / this.audioElement.duration) * 100;
            this.progressIndicator.style.width = progressPercent + '%';
            this.progressBarArea.setAttribute('aria-valuenow', Math.round(progressPercent));
        }
    }
    
    updateTimeDisplay() {
        const current = this.formatTime(this.audioElement.currentTime);
        const duration = this.audioElement.duration && !isNaN(this.audioElement.duration) 
            ? this.formatTime(this.audioElement.duration) 
            : '0:00';
        this.currentTimeEl.textContent = current;
        this.durationEl.textContent = duration;
    }
    
    formatTime(seconds) {
        if (isNaN(seconds)) return '0:00';
        const mins = Math.floor(seconds / 60);
        const secs = Math.floor(seconds % 60);
        return `${mins}:${secs.toString().padStart(2, '0')}`;
    }
    
    seek(e) {
        const rect = this.progressBarArea.getBoundingClientRect();
        const clickX = e.clientX - rect.left;
        const width = rect.width;
        const percentage = Math.max(0, Math.min(1, clickX / width));
        
        if (this.audioElement.duration) {
            this.audioElement.currentTime = percentage * this.audioElement.duration;
        }
    }
    
    addEventListeners() {
        // Close
        this.closeBtn.addEventListener('click', () => this.closePlayer());
        
        // Close on overlay click
        this.playerOverlay.addEventListener('click', (e) => {
            if (e.target === this.playerOverlay) {
                this.closePlayer();
            }
        });
        
        // Controls
        this.playBtn.addEventListener('click', () => this.togglePlayPause());
        this.prevBtn.addEventListener('click', () => this.previousTrack());
        this.nextBtn.addEventListener('click', () => this.nextTrack());
        
        // Progress bar
        this.progressBarArea.addEventListener('click', (e) => this.seek(e));
        
        // Progress bar keyboard
        this.progressBarArea.addEventListener('keydown', (e) => {
            if (e.key === 'ArrowLeft') {
                e.preventDefault();
                this.audioElement.currentTime = Math.max(0, this.audioElement.currentTime - 5);
            } else if (e.key === 'ArrowRight') {
                e.preventDefault();
                this.audioElement.currentTime = Math.min(this.audioElement.duration || 0, this.audioElement.currentTime + 5);
            }
        });
        
        // Audio events
        this.audioElement.addEventListener('timeupdate', () => {
            this.updateProgress();
            this.updateTimeDisplay();
        });
        
        this.audioElement.addEventListener('loadedmetadata', () => {
            this.updateTimeDisplay();
        });
        
        this.audioElement.addEventListener('ended', () => {
            this.nextTrack();
        });
        
        this.audioElement.addEventListener('error', (e) => {
            console.error('Audio error:', e);
            this.pause();
        });
        
        // Keyboard shortcuts
        document.addEventListener('keydown', (e) => {
            if (this.playerOverlay.style.display !== 'flex') return;
            if (e.target.tagName === 'INPUT' || e.target.tagName === 'BUTTON') return;
            
            switch(e.key) {
                case 'Escape':
                    this.closePlayer();
                    break;
                case ' ':
                    e.preventDefault();
                    this.togglePlayPause();
                    break;
                case 'ArrowLeft':
                    e.preventDefault();
                    this.previousTrack();
                    break;
                case 'ArrowRight':
                    e.preventDefault();
                    this.nextTrack();
                    break;
            }
        });
    }
}

// Initialize global instance
window.rokkoAudioPlayer = null;

// Auto-initialize when DOM is ready
if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', () => {
        window.rokkoAudioPlayer = new TemplateAudioPlayer();
    });
} else {
    window.rokkoAudioPlayer = new TemplateAudioPlayer();
}
